"""Writes the shared <head> fonts, header and footer into every page.

Run from the repo root:  python3 scripts/shared.py
Each page keeps its own body content. The header and footer live between
<!-- SHARED:HEADER --> ... <!-- /SHARED:HEADER --> and
<!-- SHARED:FOOTER --> ... <!-- /SHARED:FOOTER --> markers.
"""
import re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGES = {  # path: (prefix to root, current nav key)
    "index.html": ("", "home"),
    "pricing/index.html": ("../", "pricing"),
    "support/index.html": ("../", "support"),
    "support/thanks/index.html": ("../../", "support"),
    "privacy/index.html": ("../", "privacy"),
    "terms/index.html": ("../", "terms"),
    "codecamp/index.html": ("../", "codecamp"),
}
FONTS = ('<link rel="preconnect" href="https://fonts.googleapis.com">\n'
         '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\n'
         '<link href="https://fonts.googleapis.com/css2?family=Poppins:wght@400;500;600;700&display=swap" rel="stylesheet">')

def header(p, cur):
    def nav(href, key, label):
        a = ' aria-current="page"' if key == cur else ""
        return f'<a href="{href}"{a}>{label}</a>'
    links = [nav(f"{p}#how", "how", "How it works"), nav(f"{p}pricing/", "pricing", "Pricing"),
             nav(f"{p}support/", "support", "Support"), nav(f"{p}privacy/", "privacy", "Privacy")]
    return f'''<!-- SHARED:HEADER (generated by scripts/shared.py) -->
<a class="skip" href="#main">Skip to content</a>
<header class="site-head">
  <div class="wrap">
    <!-- LOGO: letters-only placeholder. Swap for the Nutmeg-on-top logo when it is exported. -->
    <a class="brand" href="{p or './'}" aria-label="PretendThat home"><img src="{p}assets/art/logo-pretendthat.svg" width="1484" height="633" alt="PretendThat"></a>
    <nav class="site-nav" aria-label="Main">
      {"\n      ".join(links)}
    </nav>
    <a class="btn-chunky small head-cta" href="{p}#download">Get the app</a>
    <details class="menu-toggle">
      <summary aria-label="Open menu">Menu <svg width="18" height="18" viewBox="0 0 24 24" aria-hidden="true"><path d="M4 7h16M4 12h16M4 17h16" stroke="currentColor" stroke-width="2.6" stroke-linecap="round"/></svg></summary>
      <nav class="menu-panel" aria-label="Main (mobile)">
        {"\n        ".join(links)}
        <a href="{p}#download">Get the app</a>
      </nav>
    </details>
  </div>
</header>
<!-- /SHARED:HEADER -->'''

def footer(p, after_closing):
    cls = "site-foot after-closing" if after_closing else "site-foot"
    return f'''<!-- SHARED:FOOTER (generated by scripts/shared.py) -->
<footer class="{cls}">
  <div class="wrap">
    <div class="foot-grid">
      <div>
        <!-- Nutmeg-on-top logo (transparent) on a white badge: the footer is dark purple, and the purple "that" needs a light background. -->
        <a class="foot-logo" href="{p or './'}" aria-label="PretendThat home"><img src="{p}assets/art/logo-nutmeg-top-460.webp" srcset="{p}assets/art/logo-nutmeg-top-460.webp 1x, {p}assets/art/logo-nutmeg-top-920.webp 2x" width="460" height="321" alt="PretendThat" loading="lazy"></a>
        <p class="mt-5 max-w-[34ch]">Pretend-play adventures for kids 4–8, planned by talking and played off the screen.</p>
      </div>
      <div>
        <h2>Explore</h2>
        <ul>
          <li><a href="{p}#how">How it works</a></li>
          <li><a href="{p}pricing/">Pricing</a></li>
          <li><a href="{p}#faq">Questions</a></li>
        </ul>
      </div>
      <div>
        <h2>Help</h2>
        <ul>
          <li><a href="{p}support/">Support</a></li>
          <li><a href="{p}support/#contact">Contact us</a></li>
          <li><a href="mailto:support@pretendthat.app">support@pretendthat.app</a></li>
        </ul>
      </div>
      <div>
        <h2>The fine print</h2>
        <ul>
          <li><a href="{p}privacy/">Privacy</a></li>
          <li><a href="{p}terms/">Terms</a></li>
          <li><a href="{p}codecamp/">Code Camp 2026</a></li>
        </ul>
      </div>
    </div>
    <div class="fine">
      <span>© 2026 PretendThat</span>
      <a href="{p}codecamp/">Made at Southern Utah Code Camp 2026 — 1st place</a>
    </div>
  </div>
</footer>
<!-- /SHARED:FOOTER -->'''

for rel, (p, cur) in PAGES.items():
    f = ROOT / rel
    s = f.read_text()
    # fonts
    s = re.sub(r'<link rel="preconnect" href="https://fonts.googleapis.com">\s*<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>\s*<link href="https://fonts.googleapis.com/css2[^"]*" rel="stylesheet">', FONTS, s)
    # header: replace marker block, or the old skip link + header
    h = header(p, cur)
    if "<!-- SHARED:HEADER" in s:
        s = re.sub(r"<!-- SHARED:HEADER.*?<!-- /SHARED:HEADER -->", lambda m: h, s, flags=re.S)
    else:
        s, n = re.subn(r'(<a class="skip"[^\n]*\n\s*)?<header class="site-head">.*?</header>', lambda m: h, s, count=1, flags=re.S)
        assert n == 1, rel
    ft = footer(p, 'class="closing' in s)
    if "<!-- SHARED:FOOTER" in s:
        s = re.sub(r"<!-- SHARED:FOOTER.*?<!-- /SHARED:FOOTER -->", lambda m: ft, s, flags=re.S)
    else:
        s, n = re.subn(r'<footer class="site-foot">.*?</footer>', lambda m: ft, s, count=1, flags=re.S)
        assert n == 1, rel
    f.write_text(s)
    print("ok", rel)
